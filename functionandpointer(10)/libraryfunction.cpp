#include<iostream>
#include<cmath>//library file
using namespace std;

int main(){
    cout<<sqrt(4)<<endl;//for square root
    cout<<cbrt(4)<<endl;//for cube root
    cout<<max(4,7)<<endl;//for maximum out of two 
    cout<<min(4,7)<<endl;//for minimum out of two 
    cout<<pow(4,3)<<endl;//for power 
}